// == Начало 1 кода ==
#include <iostream>
#include <cstdlib>
#include <ctime>
#include <vector>
#include <string>
#include <iomanip>
#include <sstream>
using namespace std;

int main()
{
    srand(static_cast<unsigned>(time(nullptr))); // Инициализация генератора псевдослучайных чисел.
    setlocale(LC_ALL, "rus");

    int N;
    double a, b;
    int K;

    cout << "Введите количество чисел N: ";
    cin >> N;
    cout << "Введите границы интервала [a, b] через пробел: ";
    cin >> a >> b;
    cout << "Введите число интервалов K: ";
    cin >> K;

    // Генерация массива случайных чисел
    vector<double> numbers(N);                 // Создаём вектор numbers размера N для вещественных чисел
    for (int i = 0; i < N; i++)                // Проходим по всем N элементам массива
    {
        numbers[i] = a + (b - a) * (rand() / (RAND_MAX + 1.0));
        // Заполняем i-й элемент случайным числом из диапазона [a, b)
        // rand() / (RAND_MAX + 1.0) даёт число от 0 до 1, не включая 1
        // Умножаем на длину интервала (b - a) и прибавляем a
    }

    // Подсчёт попаданий в интервалы
    double step = (b - a) / K; // Вычисляем ширину одного интервала (шаг) для гистограммы
    vector<int> counts(K, 0); // Создаём вектор counts из K счётчиков, изначально все равны 0

    for (int i = 0; i < N; i++) // Проходим по всем сгенерированным числам
    {
        int index = static_cast<int>((numbers[i] - a) / step);
        // Определяем номер интервала, в который попало число:
        // (число - a) / step даёт дробный индекс, приводим к int — получаем номер кармана

        if (index >= K) index = K - 1; // Если число попало ровно в правую границу b, индекс может стать K
        // Тогда относим его к последнему интервалу с номером K - 1

        counts[index]++; // Увеличиваем счётчик для найденного интервала
    }

    // Наибольшее значение среди счётчиков
    int maxCount = 0; // Переменная для максимального количества попаданий в один интервал
    for (int i = 0; i < K; i++) // Проходим по всем интервалам
    {
        if (counts[i] > maxCount) maxCount = counts[i]; // Если текущий счётчик больше максимума — обновляем максимум
    }

    const int MAX_BAR_LENGTH = 50; // Максимальная длина столбика гистограммы в символах '*'

    // Формируем строки гистограммы
    vector<string> lines; // Вектор строк, в котором будем собирать готовые строки гистограммы
    for (int i = 0; i < K; i++) // Проходим по всем K интервалам
    {
        double left = a + i * step; // Левая граница i-го интервала
        double right = left + step; // Правая граница i-го интервала

        int barLength = (maxCount == 0) ? 0 : (int)(1.0 * counts[i] / maxCount * MAX_BAR_LENGTH);
        // Вычисляем длину столбика пропорционально counts[i] относительно maxCount
        // Если maxCount == 0, длина равна 0, чтобы избежать деления на ноль
        // Иначе: доля от максимума умножается на MAX_BAR_LENGTH

        ostringstream oss; // Создаём строковый поток для удобного формирования строки
        oss << fixed << setprecision(2) << left << "..." << right << " ";
        // Записываем в поток левую и правую границы с двумя знаками после запятой
        // Например: 1.00...2.00 

        for (int j = 0; j < barLength; j++) oss << "*"; // Добавляем barLength символов '*'
        oss << " (" << counts[i] << ")"; // Добавляем количество попаданий в скобках

        lines.push_back(oss.str()); // Преобразуем поток в строку и добавляем в вектор lines
    }

    // Вывод гистограммы
    cout << "\nГистограмма распределения:\n"; // Выводим заголовок гистограммы
    for (int i = 0; i < K; i++) // Проходим по всем строкам гистограммы
    {
        cout << lines[i] << endl; // Выводим i-ю строку гистограммы на экран
    }

    system("PAUSE");
    return 0;
}

