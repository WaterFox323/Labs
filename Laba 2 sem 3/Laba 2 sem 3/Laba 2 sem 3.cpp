// Глобальные границы диапазона (не const, потому что вводим с клавиатуры)
int A_MIN, A_MAX;

void Get_Numbers(int& A_MIN, int& A_MAX, int& N); // функция ввода границ и размера массива

void generate(vector<int>& arr) // функция заполнения массива случайными числами
{
    for (int i = 0; i < (int)arr.size(); i++) // проходим по всем элементам массива
        arr[i] = A_MIN + rand() % (A_MAX - A_MIN + 1); // присваиваем случайное число из диапазона
}

void print(const vector<int>& arr) // функция вывода массива
{
    for (int i = 0; i < (int)arr.size(); i++) // перебираем элементы
    {
        cout << setw(7) << arr[i]; // выводим число в поле ширины 7
        if ((i + 1) % 10 == 0) cout << endl; // после каждого 10-го числа переводим строку
    }
    if (arr.size() % 10 != 0) cout << endl; // если последняя строка неполная, завершаем её переводом строки
}

bool isSorted(const vector<int>& arr) // функция проверки упорядоченности по неубыванию
{
    for (int i = 1; i < (int)arr.size(); i++) // начинаем со второго элемента
        if (arr[i - 1] > arr[i]) return false; // если предыдущий больше текущего, порядок нарушен
    return true; // если нарушений нет, массив отсортирован
}

void shellSort(vector<int>& a) // сортировка Шелла
{
    int n = (int)a.size(); // размер массива
    int d = n / 2; // начальное расстояние между сравниваемыми элементами
    while (d > 0) // пока расстояние больше нуля
    {
        for (int i = d; i < n; i++) // сортировка вставками с шагом d
        {
            int key = a[i]; // запоминаем текущий элемент
            int j = i; // индекс для движения влево с шагом d
            while (j >= d && a[j - d] > key) // пока слева есть элемент больше key
            {
                a[j] = a[j - d]; // сдвигаем больший элемент вправо
                j = j - d; // переходим к предыдущему элементу с шагом d
            }
            a[j] = key; // ставим сохранённый элемент на найденное место
        }
        d = d / 2; // уменьшаем расстояние в два раза
    }
}

void quickSortIterative(vector<int>& b) // быстрая сортировка без рекурсии
{
    int n = (int)b.size(); // размер массива
    if (n < 2) return; // если элементов меньше двух, сортировать нечего

    vector<int> stack; // стек для хранения границ подмассивов
    stack.push_back(0); // кладём нижнюю границу всего массива
    stack.push_back(n - 1); // кладём верхнюю границу всего массива

    while (!stack.empty()) // пока стек не пуст
    {
        int high = stack.back(); stack.pop_back(); // достаём верхнюю границу
        int low = stack.back();  stack.pop_back(); // достаём нижнюю границу

        int x = b[(low + high) / 2]; // опорный элемент из середины

        int i = low; // левый указатель
        int j = high; // правый указатель
        while (i <= j) // пока указатели не разошлись
        {
            while (b[i] < x) // ищем слева элемент, который не меньше опорного
                i++; // двигаем левый указатель вправо
            while (b[j] > x) // ищем справа элемент, который не больше опорного
                j--; // двигаем правый указатель влево
            if (i <= j) // если указатели ещё не разошлись
            {
                swap(b[i], b[j]); // меняем элементы местами
                i++; // сдвигаем левый указатель
                j--; // сдвигаем правый указатель
            }
        }

        if (low < j) // если слева осталась часть для сортировки
        {
            stack.push_back(low); // кладём нижнюю границу левой части
            stack.push_back(j); // кладём верхнюю границу левой части
        }
        if (i < high) // если справа осталась часть для сортировки
        {
            stack.push_back(i); // кладём нижнюю границу правой части
            stack.push_back(high); // кладём верхнюю границу правой части
        }
    }
}

void hoareSort(vector<int>& c, int low, int high) // быстрая сортировка методом Хоара
{
    if (low >= high) return; // если в подмассиве один элемент или меньше, выходим

    int x = c[(low + high) / 2]; // опорный элемент из середины

    int i = low; // левый указатель
    int j = high; // правый указатель
    while (i <= j) // пока указатели не разошлись
    {
        while (c[i] < x) // ищем слева элемент, который не меньше опорного
            i++; // двигаем левый указатель вправо
        while (c[j] > x) // ищем справа элемент, который не больше опорного
            j--; // двигаем правый указатель влево
        if (i <= j) // если указатели ещё не разошлись
        {
            swap(c[i], c[j]); // меняем элементы местами
            i++; // сдвигаем левый указатель
            j--; // сдвигаем правый указатель
        }
    }

    hoareSort(c, low, j); // рекурсивно сортируем левую часть
    hoareSort(c, i, high); // рекурсивно сортируем правую часть
}

string padRight(const string& s, int width) // выравнивание подписи по ширине с учётом кириллицы
{
    int len = 0; // счётчик символов, а не байтов
    for (unsigned char ch : s) // перебираем байты строки
        if ((ch & 0xC0) != 0x80) len++; // байты-продолжения UTF-8 не считаем
    return s + string(len < width ? width - len : 1, ' '); // добавляем пробелы до нужной ширины
}

void Get_Numbers(int& A_MIN, int& A_MAX, int& N)
{
    cout << "Введите нижнюю и верхнюю границу: ";
    cin >> A_MIN >> A_MAX;
    cout << "Введите количество элементов: ";
    cin >> N;
}

int main() // главная функция
{
    setlocale(LC_ALL, "rus");

    srand(static_cast<unsigned>(time(nullptr))); // инициализируем генератор случайных чисел текущим временем

    int N;
    Get_Numbers(A_MIN, A_MAX, N); // передаём сами переменные, а не их адреса

    vector<int> source(N); // создаём исходный массив из N элементов
    generate(source); // заполняем его случайными числами

    cout << "Исходный массив (" << N << " чисел типа int из ["
        << A_MIN << ", " << A_MAX << "]):" << endl; // выводим заголовок исходного массива
    print(source); // выводим исходный массив

    vector<int> a = source; // копия для сортировки Шелла
    vector<int> b = source; // копия для итеративной быстрой сортировки
    vector<int> c = source; // копия для рекурсивной быстрой сортировки

    shellSort(a); // сортируем первую копию сортировкой Шелла
    cout << "\n1) Сортировка Шелла (вариант 4):" << endl; // выводим заголовок
    print(a); // выводим результат
    cout << "Массив отсортирован: " << (isSorted(a) ? "да" : "нет") << endl; // проверяем упорядоченность

    quickSortIterative(b); // сортируем вторую копию итеративной быстрой сортировкой
    cout << "\n2) Быстрая сортировка без рекурсии:" << endl; // выводим заголовок
    print(b); // выводим результат
    cout << "Массив отсортирован: " << (isSorted(b) ? "да" : "нет") << endl; // проверяем упорядоченность

    hoareSort(c, 0, N - 1); // сортируем третью копию методом Хоара
    cout << "\n3) Быстрая сортировка, метод Хоара:" << endl; // выводим заголовок
    print(c); // выводим результат
    cout << "Массив отсортирован: " << (isSorted(c) ? "да" : "нет") << endl; // проверяем упорядоченность

    if (a == b && b == c) // сравниваем три отсортированных массива
        cout << "\nРезультаты совпадают" << endl; // если совпадают
    else
        cout << "\nРезультаты не совпадают" << endl; // если не совпадают

    const int K = 5; // количество разных размеров массивов для теста
    const int sizes[K] = { 1000, 10000, 100000, 500000, 1000000 }; // размеры массивов
    const char* names[3] = { "Быстрая без рекурсии",
                             "Быстрая метод Хоара",
                             "Сортировка Шелла" }; // названия методов
    double result[3][K]; // таблица результатов: 3 метода × K размеров

    for (int k = 0; k < K; k++) // перебираем все размеры массивов
    {
        vector<int> arr(sizes[k]); // создаём массив текущего размера
        generate(arr); // заполняем его случайными числами

        for (int type = 0; type < 3; type++) // перебираем три метода сортировки
        {
            vector<int> copy = arr; // делаем копию, чтобы исходный arr не менялся

            auto t1 = high_resolution_clock::now(); // засекаем время начала сортировки

            if (type == 0) quickSortIterative(copy); // выбираем итеративную быструю сортировку
            else if (type == 1) hoareSort(copy, 0, (int)copy.size() - 1); // выбираем метод Хоара
            else shellSort(copy); // выбираем сортировку Шелла

            auto t2 = high_resolution_clock::now(); // засекаем время окончания сортировки

            result[type][k] = duration_cast<microseconds>(t2 - t1).count() / 1000.0; // переводим в миллисекунды
        }
    }

    cout << "\nТаблица 2. Сравнение методов сортировки (время в миллисекундах)\n" << endl; // заголовок таблицы

    cout << padRight("Количество элементов", 24); // выводим заголовок первого столбца
    for (int k = 0; k < K; k++) // выводим размеры массивов по столбцам
        cout << setw(12) << right << sizes[k]; // выводим размер с выравниванием
    cout << endl; // переводим строку

    cout << fixed << setprecision(3); // настраиваем вывод чисел с фиксированной точкой и 3 знаками

    for (int type = 0; type < 3; type++) // выводим строки таблицы по методам
    {
        cout << padRight(names[type], 24); // название метода в первом столбце
        for (int k = 0; k < K; k++) // времена для всех размеров
            cout << setw(12) << right << result[type][k]; // выводим время с выравниванием
        cout << endl; // переводим строку
    }

    system("PAUSE"); // пауза перед закрытием окна консоли
    return 0; // успешное завершение программы
}