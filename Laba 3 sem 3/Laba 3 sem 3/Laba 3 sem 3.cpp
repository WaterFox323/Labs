#include <iostream>
#include <vector>
#include <iomanip>
#include <cstdlib>

using namespace std;

int n;                        // количество вершин графа
vector<vector<int>> adj;      // матрица смежности (adj[u][v] - число рёбер между u и v)

void addEdge(int u, int v) // функция добавления ребра u - v
{
    adj[u][v]++; // увеличиваем число рёбер u - v
    adj[v][u]++; // граф неориентированный, поэтому и v - u
}

void removeEdge(int u, int v) // функция удаления ребра u - v
{
    adj[u][v]--; // уменьшаем число рёбер u - v
    adj[v][u]--; // и v - u
}

int degree(int v) // функция вычисления степени вершины
{
    int d = 0; // счётчик рёбер
    for (int u = 1; u <= n; u++) // перебираем все вершины
        d += adj[v][u]; // прибавляем количество рёбер v - u
    return d; // возвращаем степень вершины
}

void dfs(int v, vector<bool>& visited) // обход графа в глубину
{
    visited[v] = true; // отмечаем вершину как посещённую
    for (int u = 1; u <= n; u++) // перебираем всех соседей
        if (adj[v][u] > 0 && !visited[u]) // если есть ребро и сосед ещё не посещён
            dfs(u, visited); // переходим в соседа
}

int countReachable(int v) // число вершин, достижимых из v
{
    vector<bool> visited(n + 1, false); // массив отметок посещения
    dfs(v, visited); // обходим граф из вершины v
    int cnt = 0; // счётчик достижимых вершин
    for (int u = 1; u <= n; u++) // перебираем все вершины
        if (visited[u]) cnt++; // считаем посещённые
    return cnt; // возвращаем результат
}

bool isConnected() // проверка связности графа (без учёта изолированных вершин)
{
    int start = 0; // вершина, с которой начинаем обход
    for (int v = 1; v <= n; v++) // ищем первую вершину с ненулевой степенью
        if (degree(v) > 0) { start = v; break; }
    if (start == 0) return true; // в графе нет рёбер - считаем связным
    vector<bool> visited(n + 1, false); // массив отметок посещения
    dfs(start, visited); // обходим граф
    for (int v = 1; v <= n; v++) // проверяем все вершины
        if (degree(v) > 0 && !visited[v]) return false; // вершина с рёбрами не достигнута
    return true; // все вершины с рёбрами достигнуты
}

bool isBridge(int u, int v) // проверка: является ли ребро u - v мостом
{
    if (adj[u][v] > 1) return false; // кратное ребро не может быть мостом
    int before = countReachable(u); // число достижимых вершин до удаления ребра
    removeEdge(u, v); // временно удаляем ребро
    int after = countReachable(u); // число достижимых вершин после удаления
    addEdge(u, v); // возвращаем ребро на место
    return after < before; // если стало меньше - граф распался, ребро является мостом
}

vector<int> fleury(int start) // алгоритм Флёри построения эйлерова пути (цикла)
{
    vector<vector<int>> saved = adj; // сохраняем граф, так как рёбра будут удаляться
    vector<int> path; // список вершин пути
    path.push_back(start); // начинаем с заданной вершины
    int cur = start; // текущая вершина
    while (degree(cur) > 0) // пока у текущей вершины есть рёбра
    {
        int next = 0; // следующая вершина
        for (int u = 1; u <= n; u++) // перебираем соседей по возрастанию номера
        {
            if (adj[cur][u] == 0) continue; // ребра нет - пропускаем
            if (degree(cur) == 1 || !isBridge(cur, u)) // ограничение: мост выбираем только если нет других рёбер
            {
                next = u; // нашли подходящее ребро
                break; // выходим из цикла
            }
        }
        removeEdge(cur, next); // удаляем пройденное ребро из текущего графа
        path.push_back(next); // вносим вершину в список
        cur = next; // делаем её текущей
    }
    adj = saved; // восстанавливаем исходный граф
    return path; // возвращаем построенный путь
}

int firstVertex() // первая вершина с ненулевой степенью
{
    for (int v = 1; v <= n; v++) // перебираем вершины по возрастанию
        if (degree(v) > 0) return v; // нашли вершину, у которой есть рёбра
    return 1; // рёбер нет - возвращаем вершину 1
}

void printMatrix() // вывод матрицы смежности
{
    cout << "    ";
    for (int v = 1; v <= n; v++) cout << setw(3) << v; // номера столбцов
    cout << endl;
    for (int u = 1; u <= n; u++) // строки матрицы
    {
        cout << setw(3) << u << " "; // номер строки
        for (int v = 1; v <= n; v++) cout << setw(3) << adj[u][v]; // элементы строки
        cout << endl;
    }
}

void printDegrees(vector<int>& odd) // вывод степеней вершин и поиск нечётных
{
    odd.clear(); // очищаем список вершин нечётной степени
    cout << "Степени вершин:" << endl;
    for (int v = 1; v <= n; v++) // перебираем вершины
    {
        int d = degree(v); // степень вершины v
        cout << "  d(v" << v << ") = " << d << (d % 2 ? "  (нечётная)" : "") << endl;
        if (d % 2 != 0) odd.push_back(v); // запоминаем вершину нечётной степени
    }
}

void printPath(const vector<int>& path) // вывод пути
{
    for (int i = 0; i < (int)path.size(); i++) // перебираем вершины пути
    {
        cout << "v" << path[i]; // выводим вершину
        if (i + 1 < (int)path.size()) cout << " - "; // разделитель между вершинами
    }
    cout << endl;
    cout << "Количество пройденных рёбер: " << path.size() - 1 << endl;
}

int main() // главная функция
{
    setlocale(LC_ALL, "rus");

    int m; // количество рёбер
    int choice; // выбор способа задания графа
    cout << "Использовать граф варианта 4 (1 - да, 0 - ввести свой граф): ";
    cin >> choice;

    if (choice == 1) // граф варианта 4
    {
        n = 8; // 8 вершин
        adj.assign(n + 1, vector<int>(n + 1, 0)); // создаём пустую матрицу смежности
        int edges[12][2] = { {1,2}, {1,5}, {2,4}, {2,7}, {2,8}, {3,4},
                             {3,7}, {4,5}, {4,6}, {6,7}, {6,8}, {7,8} }; // рёбра варианта 4
        m = 12; // количество рёбер
        for (int i = 0; i < m; i++) addEdge(edges[i][0], edges[i][1]); // добавляем рёбра
    }
    else // ввод графа с клавиатуры
    {
        cout << "Введите количество вершин и рёбер: ";
        cin >> n >> m;
        adj.assign(n + 1, vector<int>(n + 1, 0)); // создаём пустую матрицу смежности
        cout << "Введите рёбра (пары вершин от 1 до " << n << "):" << endl;
        for (int i = 0; i < m; i++) // читаем m рёбер
        {
            int u, v;
            cin >> u >> v;
            addEdge(u, v); // добавляем ребро
        }
    }

    cout << "\nМатрица смежности графа:" << endl;
    printMatrix(); // выводим матрицу смежности

    vector<int> odd; // вершины нечётной степени
    printDegrees(odd); // выводим степени и находим нечётные вершины

    if (!isConnected()) // эйлеровым может быть только связный граф
    {
        cout << "\nГраф несвязный - эйлеров цикл и эйлерова цепь невозможны." << endl;

        system("PAUSE"); // пауза перед закрытием окна консоли

        return 0;
    }
    cout << "\nГраф связный." << endl;
    cout << "Количество вершин нечётной степени: " << odd.size() << endl;

    if (odd.empty()) // все степени чётные
    {
        cout << "\nГраф является эйлеровым." << endl;
        cout << "Эйлеров цикл: ";
        printPath(fleury(firstVertex())); // строим цикл из первой вершины
    }
    else
    {
        if (odd.size() == 2) // ровно две вершины нечётной степени
        {
            cout << "\nГраф не является эйлеровым, но является полуэйлеровым." << endl;
            cout << "Эйлерова цепь (из v" << odd[0] << " в v" << odd[1] << "): ";
            printPath(fleury(odd[0])); // цепь начинается в одной нечётной вершине
        }
        else // нечётных вершин больше двух
            cout << "\nГраф не является ни эйлеровым, ни полуэйлеровым." << endl;

        // Изменение графа: попарно соединяем вершины нечётной степени
        cout << "\nИзменение графа для построения эйлерова цикла:" << endl;
        for (int i = 0; i + 1 < (int)odd.size(); i += 2) // берём нечётные вершины парами
        {
            int u = odd[i], v = odd[i + 1]; // пара вершин нечётной степени
            if (adj[u][v] == 0) // если вершины не смежны
            {
                addEdge(u, v); // добавляем ребро между ними
                cout << "  добавлено ребро v" << u << " - v" << v << endl;
            }
            else // вершины уже смежны - добавляем новую вершину, чтобы не было кратных рёбер
            {
                n++; // новая вершина с номером n
                for (int k = 1; k < n; k++) adj[k].push_back(0); // расширяем строки матрицы
                adj.push_back(vector<int>(n + 1, 0)); // добавляем новую строку
                addEdge(u, n); // ребро u - новая вершина
                addEdge(n, v); // ребро новая вершина - v
                cout << "  добавлена вершина v" << n << " и рёбра v" << u << " - v" << n
                    << ", v" << n << " - v" << v << endl;
            }
        }

        cout << "\nМатрица смежности изменённого графа:" << endl;
        printMatrix(); // выводим новую матрицу
        printDegrees(odd); // проверяем степени

        if (odd.empty() && isConnected()) // теперь все степени чётные
        {
            cout << "\nИзменённый граф является эйлеровым." << endl;
            cout << "Эйлеров цикл: ";
            printPath(fleury(firstVertex())); // строим эйлеров цикл
        }
    }

    system("PAUSE");

    return 0;
}