// Программа сравнивает по скорости три сортировки из Задания 1
// (быстрая без рекурсии, быстрая методом Хоара, сортировка Шелла)
// на массивах разного размера и выводит результаты в виде таблицы
// (время выполнения каждой сортировки в миллисекундах).

#include <iostream>     // cin, cout - потоки ввода/вывода
#include <cstdlib>      // rand(), srand() - генератор случайных чисел
#include <ctime>        // time() - текущее время, "семя" для srand()
#include <chrono>       // high_resolution_clock - высокоточный таймер для замера времени
#include <vector>       // vector - динамический массив
#include <iomanip>      // setw, fixed, setprecision - форматирование вывода чисел
#include <algorithm>    // swap - обмен значений двух переменных
#include <string>       // string - работа со строками (для подписей таблицы)

using namespace std;
using namespace std::chrono;   // чтобы не писать chrono:: перед high_resolution_clock, duration_cast и т.д.

const int A_MIN = 10040;   // нижняя граница диапазона случайных чисел (вариант 4)
const int A_MAX = 30704;   // верхняя граница диапазона случайных чисел (вариант 4)

// Заполнение массива случайными числами типа int из диапазона [A_MIN, A_MAX]
void generate(vector<int>& a)
{
    for (size_t i = 0; i < a.size(); ++i)
        a[i] = A_MIN + rand() % (A_MAX - A_MIN + 1);   // число из [A_MIN, A_MAX]
}

// --------- Сортировка Шелла (сортировка варианта 4) ---------
// (алгоритм полностью совпадает с Заданием 1, см. подробные пояснения там)
void shellSort(vector<int>& a)
{
    int n = (int)a.size();                 // количество элементов
    for (int d = n / 2; d > 0; d /= 2)     // шаг d уменьшается вдвое на каждой итерации: N/2, N/4, ..., 1
    {
        for (int i = d; i < n; ++i)        // вставка элемента i в уже "прошаренную" шагом d часть массива
        {
            int key = a[i];                // запоминаем вставляемый элемент
            int j = i;                     // позиция для вставки
            while (j >= d && a[j - d] > key)   // сдвигаем вправо элементы, которые больше key
            {
                a[j] = a[j - d];
                j -= d;
            }
            a[j] = key;                    // ставим key на освободившееся место
        }
    }
}

// --------- Быстрая сортировка без рекурсии ---------
// (алгоритм полностью совпадает с Заданием 1: границы участков хранятся
// в собственном стеке-векторе вместо рекурсивных вызовов)
void quickSortIterative(vector<int>& a)
{
    int n = (int)a.size();
    if (n < 2) return;                     // массив из 0-1 элемента уже отсортирован

    vector<int> stack;                     // стек границ [low, high] необработанных участков
    stack.push_back(0);
    stack.push_back(n - 1);

    while (!stack.empty())                 // пока есть необработанные участки
    {
        int high = stack.back(); stack.pop_back();   // забираем правую границу
        int low = stack.back(); stack.pop_back();     // забираем левую границу

        int x = a[(low + high) / 2];       // опорный элемент из середины участка
        int i = low, j = high;
        while (i <= j)                     // разбиение участка на две части относительно x
        {
            while (a[i] < x) ++i;
            while (a[j] > x) --j;
            if (i <= j) { swap(a[i], a[j]); ++i; --j; }
        }

        if (low < j) { stack.push_back(low); stack.push_back(j); }   // левая часть - на дальнейшую обработку
        if (i < high) { stack.push_back(i);   stack.push_back(high); } // правая часть - на дальнейшую обработку
    }
}

// --------- Быстрая сортировка, рекурсивный метод Хоара ---------
// (алгоритм полностью совпадает с Заданием 1: рекурсивное разбиение
// участка [low, high] относительно опорного элемента)
void hoareSort(vector<int>& a, int low, int high)
{
    if (low >= high) return;               // участок из одного элемента упорядочен

    int x = a[(low + high) / 2];           // опорный элемент из середины участка
    int i = low, j = high;
    while (i <= j)
    {
        while (a[i] < x) ++i;              // ищем слева элемент не меньше опорного
        while (a[j] > x) --j;              // ищем справа элемент не больше опорного
        if (i <= j) { swap(a[i], a[j]); ++i; --j; }   // меняем местами и сдвигаем указатели
    }
    hoareSort(a, low, j);                  // сортируем левую часть
    hoareSort(a, i, high);                 // сортируем правую часть
}

// Выравнивание подписи по ширине столбца (с учётом кириллицы)
// Обычная функция дополнения строки пробелами не подходит для кириллицы,
// потому что каждая русская буква в кодировке UTF-8 занимает 2 байта,
// а .size() считает именно байты, а не отображаемые символы.
string padRight(const string& s, int width)
{
    int len = 0;                                    // здесь будем считать реальное число символов (не байт)
    for (unsigned char c : s)                        // проходим по каждому байту строки
        // (c & 0xC0) != 0x80 - проверка, что байт НЕ является "продолжением"
        // многобайтового UTF-8 символа (продолжающие байты имеют вид 10xxxxxx);
        // так мы считаем только "начальные" байты, то есть реальные символы
        if ((c & 0xC0) != 0x80) ++len;
    // дополняем строку пробелами до нужной ширины; если строка уже длиннее
    // width, добавляем хотя бы один пробел-разделитель
    return s + string(len < width ? width - len : 1, ' ');
}

// Замер времени работы сортировки в миллисодержащих единицах (мс)
// Параметр a передаётся по значению (копируется), чтобы сама функция
// measure не портила исходный массив - каждый замер стартует с одного
// и того же неотсортированного набора чисел
double measure(vector<int> a, int type)
{
    auto t1 = high_resolution_clock::now();          // точка замера: старт таймера
    if (type == 0) quickSortIterative(a);            // type 0 - быстрая сортировка без рекурсии
    else if (type == 1) hoareSort(a, 0, (int)a.size() - 1);  // type 1 - быстрая сортировка методом Хоара
    else shellSort(a);                               // type 2 (иначе) - сортировка Шелла
    auto t2 = high_resolution_clock::now();          // точка замера: финиш таймера
    // разница между t2 и t1 переводится в микросекунды, затем делится на 1000,
    // чтобы получить время в миллисекундах с дробной частью
    return duration_cast<microseconds>(t2 - t1).count() / 1000.0;
}

int main()
{
    setlocale(LC_ALL, "rus");                         // корректное отображение русских букв в консоли
    srand(static_cast<unsigned>(time(nullptr)));       // инициализация генератора случайных чисел

    // набор размеров массивов, на которых будем сравнивать сортировки
    const int sizes[] = { 1000, 10000, 100000, 500000, 1000000 };
    const int K = 5;                                  // количество разных размеров массива (длина sizes)
    double result[3][K];                              // result[тип сортировки][номер размера] = время в мс

    // для каждого размера массива...
    for (int k = 0; k < K; ++k)
    {
        vector<int> a(sizes[k]);                      // создаём массив нужного размера
        generate(a);                                  // заполняем его случайными числами
        // (один и тот же массив используется для всех трёх
        // сортировок, чтобы сравнение было честным)
        for (int type = 0; type < 3; ++type)          // для каждого из трёх типов сортировки
            result[type][k] = measure(a, type);        // замеряем время сортировки копии массива a
    }

    // подписи строк таблицы, соответствующие type = 0, 1, 2
    const char* names[3] = { "Быстрая без рекурсии",
                             "Быстрая метод Хоара",
                             "Сортировка Шелла" };

    cout << "\nТаблица 2. Сравнение методов сортировки (время в миллисекундах)\n" << endl;

    cout << padRight("Количество элементов", 24);     // заголовок первого столбца (название строк)
    // выводим заголовки столбцов - размеры массивов, каждый в поле шириной 12 символов
    for (int k = 0; k < K; ++k) cout << setw(12) << right << sizes[k];
    cout << endl;

    cout << fixed << setprecision(3);                 // числа времени выводим с 3 знаками после запятой
    for (int type = 0; type < 3; ++type)               // строка таблицы - на каждый тип сортировки
    {
        cout << padRight(names[type], 24);             // название метода сортировки (первый столбец)
        // время выполнения этого метода для каждого размера массива
        for (int k = 0; k < K; ++k) cout << setw(12) << right << result[type][k];
        cout << endl;
    }

    system("PAUSE");                                   // держим консоль открытой после завершения программы
    return 0;                                           // успешное завершение программы
}