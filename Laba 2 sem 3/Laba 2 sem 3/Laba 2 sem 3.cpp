// Программа генерирует случайный массив чисел и сортирует его
// тремя разными способами: сортировкой Шелла, быстрой сортировкой
// без рекурсии (со стеком) и быстрой сортировкой методом Хоара
// (рекурсивно). В конце сравнивается, что все три метода дали
// одинаковый результат.

#include <iostream>     // cin, cout - потоки ввода/вывода
#include <cstdlib>      // rand() - генератор случайных чисел, srand() - его инициализация
#include <ctime>        // time() - текущее время, используется как "семя" для srand()
#include <vector>       // vector - динамический массив
#include <iomanip>      // setw - манипулятор для задания ширины поля вывода
#include <algorithm>    // swap - функция обмена значений двух переменных

using namespace std;    // чтобы не писать std:: перед cout, cin, vector и т.д.

const int A_MIN = 10040;   // нижняя граница диапазона случайных чисел (вариант 4)
const int A_MAX = 30704;   // верхняя граница диапазона случайных чисел (вариант 4)

// Заполнение массива случайными числами типа int из диапазона [A_MIN, A_MAX]
void generate(vector<int>& a)
{
    // проходим по всем индексам массива от 0 до a.size()-1
    for (size_t i = 0; i < a.size(); ++i)
        // rand() % (A_MAX - A_MIN + 1) даёт число от 0 до (A_MAX - A_MIN),
        // прибавление A_MIN сдвигает диапазон к [A_MIN, A_MAX]
        a[i] = A_MIN + rand() % (A_MAX - A_MIN + 1);
}

// Вывод массива по 10 чисел в строке
void print(const vector<int>& a)
{
    // проходим по всем элементам массива по порядку
    for (size_t i = 0; i < a.size(); ++i)
    {
        // выводим очередное число, отводя под него поле шириной 7 символов
        cout << setw(7) << a[i];
        // если вывели уже 10 чисел подряд (i+1 кратно 10) - переходим на новую строку
        if ((i + 1) % 10 == 0) cout << endl;
    }
    // если размер массива не кратен 10, последняя неполная строка внутри
    // цикла не завершилась переводом строки - делаем это здесь
    if (a.size() % 10 != 0) cout << endl;
}

// Проверка упорядоченности массива по неубыванию (a[0] <= a[1] <= a[2] ...)
bool isSorted(const vector<int>& a)
{
    // сравниваем каждую пару соседних элементов, начиная со второго
    for (size_t i = 1; i < a.size(); ++i)
        // как только нашли пару, где предыдущий элемент больше следующего -
        // порядок нарушен, сразу возвращаем false
        if (a[i - 1] > a[i]) return false;
    // ни одного нарушения не найдено - массив отсортирован
    return true;
}

// --------- 1. Сортировка Шелла (сортировка варианта 4) ---------
// Идея: обобщённая сортировка вставками. Сначала сравниваются и
// переставляются элементы, стоящие далеко друг от друга (с шагом d),
// затем шаг постепенно уменьшается вплоть до 1 (в конце это уже
// обычная сортировка вставками, но массив уже почти упорядочен).
void shellSort(vector<int>& a)
{
    int n = (int)a.size();                       // n - количество элементов в массиве
    // d - текущий шаг сравнения элементов: начинаем с n/2 и каждый раз
    // делим пополам, цикл идёт, пока d не станет равным 0
    for (int d = n / 2; d > 0; d /= 2)           // шаг d: N/2, N/4, ..., 1
    {
        // для каждого элемента начиная с позиции d выполняем "вставку"
        // относительно элементов, отстоящих от него на шаг d
        for (int i = d; i < n; ++i)
        {
            int key = a[i];                      // запоминаем элемент, который будем вставлять
            int j = i;                            // j - позиция, куда в итоге встанет key
            // пока не вышли за левый край группы (j >= d) и элемент через
            // шаг d слева больше key - сдвигаем его вправо, освобождая место
            while (j >= d && a[j - d] > key)     // сдвиг вправо элементов,
            {                                    // больших текущего
                a[j] = a[j - d];                  // переносим больший элемент на позицию j
                j -= d;                           // смещаем указатель на шаг назад
            }
            a[j] = key;                          // вставка на своё место
        }
    }
}

// --------- 2. Быстрая сортировка без рекурсии (на собственном стеке) ---------
// Тот же алгоритм разделения, что и в методе Хоара, но вместо
// рекурсивных вызовов функции границы необработанных участков
// [low, high] кладутся в отдельный вектор, который используется как стек.
void quickSortIterative(vector<int>& a)
{
    int n = (int)a.size();
    if (n < 2) return;                 // массив из 0 или 1 элемента уже отсортирован

    vector<int> stack;                 // стек границ необработанных участков
    stack.push_back(0);                // кладём в стек левую границу всего массива
    stack.push_back(n - 1);            // кладём в стек правую границу всего массива

    // пока в стеке остаются необработанные участки - обрабатываем их
    while (!stack.empty())
    {
        int high = stack.back(); stack.pop_back();   // снимаем правую границу текущего участка
        int low = stack.back(); stack.pop_back();     // снимаем левую границу текущего участка

        int x = a[(low + high) / 2];   // опорный элемент - берём из середины участка
        int i = low, j = high;         // i - указатель слева, j - указатель справа
        while (i <= j)                 // разделение участка на две части
        {
            while (a[i] < x) ++i;      // ищем слева элемент, который не меньше опорного
            while (a[j] > x) --j;      // ищем справа элемент, который не больше опорного
            if (i <= j) { swap(a[i], a[j]); ++i; --j; }  // меняем их местами, сдвигаем указатели навстречу
        }

        // если слева от j осталось больше одного элемента - кладём этот участок в стек
        if (low < j) { stack.push_back(low); stack.push_back(j); }
        // если справа от i осталось больше одного элемента - кладём этот участок в стек
        if (i < high) { stack.push_back(i);   stack.push_back(high); }
    }
}

// --------- 3. Быстрая сортировка, рекурсивный метод Хоара ---------
// Классическая рекурсивная реализация: участок [low, high] делится
// относительно опорного элемента x на две части, каждая из которых
// затем сортируется рекурсивным вызовом этой же функции.
void hoareSort(vector<int>& a, int low, int high)
{
    if (low >= high) return;           // участок из одного (или нуля) элемента уже упорядочен

    int x = a[(low + high) / 2];       // базовый (разделяющий) элемент - берём из середины участка
    int i = low, j = high;             // i - указатель слева, j - указатель справа
    while (i <= j)
    {
        while (a[i] < x) ++i;          // просмотр слева: ищем элемент не меньше опорного
        while (a[j] > x) --j;          // просмотр справа: ищем элемент не больше опорного
        if (i <= j)                    // если указатели ещё не "разминулись"
        {
            swap(a[i], a[j]);          // меняем местами найденные "неправильно стоящие" элементы
            ++i; --j;                  // сдвигаем оба указателя навстречу друг другу
        }
    }
    hoareSort(a, low, j);              // рекурсивно сортируем левую часть [low, j]
    hoareSort(a, i, high);             // рекурсивно сортируем правую часть [i, high]
}

int main()
{
    setlocale(LC_ALL, "rus");                          // включаем корректное отображение русских букв в консоли
    srand(static_cast<unsigned>(time(nullptr)));        // инициализируем генератор случайных чисел текущим временем,
    // чтобы при каждом запуске получались разные числа

    int N;                                              // здесь будет храниться размер массива
    cout << "Введите количество элементов N: ";
    cin >> N;                                           // считываем размер массива, введённый пользователем

    vector<int> source(N);                              // создаём вектор длины N - исходный массив
    generate(source);                                   // заполняем его случайными числами из диапазона [A_MIN, A_MAX]

    cout << "\nИсходный массив (" << N << " чисел типа int из ["
        << A_MIN << ", " << A_MAX << "]):" << endl;
    print(source);                                      // печатаем исходный (ещё неотсортированный) массив

    vector<int> a = source;                             // делаем копию исходного массива в a
    shellSort(a);                                       // сортируем эту копию сортировкой Шелла
    cout << "\n1) Сортировка Шелла (вариант 4):" << endl;
    print(a);                                           // печатаем результат сортировки
    cout << "Массив отсортирован: " << (isSorted(a) ? "да" : "нет") << endl;  // проверяем корректность

    vector<int> b = source;                             // делаем ещё одну копию исходного массива в b
    quickSortIterative(b);                              // сортируем её быстрой сортировкой без рекурсии
    cout << "\n2) Быстрая сортировка без рекурсии:" << endl;
    print(b);                                           // печатаем результат
    cout << "Массив отсортирован: " << (isSorted(b) ? "да" : "нет") << endl;  // проверяем корректность

    vector<int> c = source;                             // делаем третью копию исходного массива в c
    hoareSort(c, 0, N - 1);                             // сортируем её рекурсивным методом Хоара
    cout << "\n3) Быстрая сортировка, метод Хоара:" << endl;
    print(c);                                           // печатаем результат
    cout << "Массив отсортирован: " << (isSorted(c) ? "да" : "нет") << endl;  // проверяем корректность

    // сравниваем все три отсортированных массива между собой:
    // если все три алгоритма реализованы верно, они дадут один и тот же
    // отсортированный массив, и оператор == для vector сравнит их поэлементно
    cout << "\nРезультаты всех трёх сортировок совпадают: "
        << ((a == b && b == c) ? "да" : "нет") << endl;

    system("PAUSE");                                    // не даём консоли закрыться сразу (актуально для Windows)
    return 0;                                           // 0 означает успешное завершение программы
}

