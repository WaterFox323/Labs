//// Гистограмма - это графическое представление данных в виде столбчатой диаграммы, которая показывает
//// распределение непрерывных числовых значений. Она визуализирует, как часто значения попадают в определённые интервалы.

#include <iostream>
#include <string>
#include <vector>
#include <fstream>
#include <ctime>
#include <cstdlib>

using namespace std;

int main() {
    // Настройка для корректного отображения русских букв в консоли (Windows)
    // Если вы используете Linux или MacOS, эта строка не обязательна, но не помешает
    setlocale(LC_ALL, "Russian");

    // Инициализация генератора случайных чисел
    srand(static_cast<unsigned int>(time(0)));

    // Список слов для игры
    //vector<string> words = { "PINEAPPLE", "PEN", "MONSTER", "STUDENT", "EXAM" }; // 1 вариант решения задания с заготовленным списком в векторе.
    
    // 2 вариант решения задачи - считывать слова с отдельного файла.
    ifstream inFile("words.txt"); // открывает файл words.txt для чтения
    vector<string> words;         // вектор строк, куда будут сложены строки из файла
    string line;                  // временная строка для чтения очередной строки

    while (getline(inFile, line)) // пока удаётся прочитать строку из файла в line
    {
        words.push_back(line);    // добавляет прочитанную строку в конец вектора words
    }

    // Выбор случайного слова
    string secretWord = words[rand() % words.size()];

    // Текущее состояние слова (изначально все буквы заменены на прочерки)
    string currentWord(secretWord.length(), '_');

    // Начальные очки
    int points = 15;

    // Алфавит для отображения (все буквы нарисованы)
    string alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
    string guessedLetters = ""; // Строка для хранения уже названных букв

    cout << "=========================================" << endl;
    cout << "       Игра 'Поле чудес'!" << endl;
    cout << "=========================================" << endl;
    cout << "У вас 15 очков. Угадайте слово!" << endl;

    // Игровой цикл: пока есть очки и слово не угадано
    while (points > 0 && currentWord != secretWord) {

        // 1. Отображаем текущее состояние слова
        cout << "\nСлово: ";
        for (char c : currentWord) {
            cout << c << " ";
        }
        cout << "\nОчки: " << points << endl;

        // 2. Отображаем алфавит (все буквы нарисованы)
        cout << "Алфавит: ";
        for (char c : alphabet) {
            if (guessedLetters.find(c) != string::npos) {
                cout << ". "; // Буква уже называлась, скрываем её
            }
            else {
                cout << c << " "; // Буква еще не называлась
            }
        }
        cout << endl;

        // 3. Запрашиваем букву у игрока
        char guess;
        cout << "Введите букву: ";
        cin >> guess;

        // 4. Проверка корректности ввода
        if (guessedLetters.find(guess) != string::npos) {
            cout << "Вы уже называли эту букву! Попробуйте другую." << endl;
            continue;
        }

        if (alphabet.find(guess) == string::npos) {
            cout << "Ошибка: введите букву на английском!" << endl;
            continue;
        }

        // Добавляем букву в список названных
        guessedLetters += guess;

        // 5. Проверяем, есть ли буква в загаданном слове
        bool found = false;
        for (size_t i = 0; i < secretWord.length(); ++i) {
            if (secretWord[i] == guess) {
                currentWord[i] = guess; // Подставляем букву вместо прочерка
                found = true;
            }
        }

        // 6. Обрабатываем результат хода
        if (found) {
            cout << "Есть такая буква!" << endl;
        }
        else {
            points--; // Штраф
            cout << "Нет такой буквы. Вы теряете одно очко." << endl;
        }
    }

    // 7. Конец игры
    cout << "\n=========================================" << endl;
    if (currentWord == secretWord) {
        cout << "ПОЗДРАВЛЯЕМ! Вы угадали слово: " << secretWord << endl;
        cout << "У вас осталось очков: " << points << endl;
    }
    else {
        cout << "Игра окончена. Вы проиграли." << endl;
        cout << "Загаданное слово было: " << secretWord << endl;
    }
    cout << "=========================================" << endl;

    system("PAUSE");
    return 0;
}