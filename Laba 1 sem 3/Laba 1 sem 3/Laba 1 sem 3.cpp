#include <iostream>
#include <string>
#include <vector>
#include <fstream>
#include <ctime>
#include <cstdlib>
    using namespace std;

    int main()
    {
        setlocale(LC_ALL, "russ");
        srand(static_cast<unsigned int>(time(0))); // Инициализирует генератор случайных чисел текущим временем, чтобы rand() выдавал разные значения при каждом запуске.

        // Формируем список слов
        ifstream inFile("words.txt"); // Открывает файл words.txt для чтения.
        vector<string> words; // Создаёт вектор строк, в котором будут храниться слова из файла.
        string line; // Временная переменная для чтения одной строки из файла.
        while (getline(inFile, line)) // Пока из файла удаётся считать очередную строку...
        {
            words.push_back(line); // ...добавляет эту строку в вектор words.
        }

        string secretWord = words[rand() % words.size()]; // Выбирает случайное слово из вектора: rand() % количество_слов.
        string currentWord(secretWord.length(), '_'); // Создаёт строку из символов '_' такой же длины, как загаданное слово.

        int points = 15; // Начальное количество очков игрока.
        string alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"; // Строка с английским алфавитом. Только заглавные буквы.
        string guessedLetters = ""; // Здесь хранятся буквы, которые игрок уже называл.

        cout << "Игра 'Поле чудес'!" << endl; // Выводит название игры.
        cout << "У вас 15 очков. Угадайте слово!" << endl; // Выводит начальное сообщение игроку.

        while (points > 0 && currentWord != secretWord) // Игра продолжается, пока есть очки и слово ещё не угадано.
        {
            cout << "\nСлово: "; // Выводит подпись перед текущим состоянием слова.
            for (char c : currentWord) cout << c << " "; // Выводит currentWord посимвольно через пробел: открытые буквы и '_'.
            cout << "\nОчки: " << points << endl; // Показывает текущее количество очков.

            cout << "Алфавит: "; // Подпись перед алфавитом.
            for (char c : alphabet) // Перебирает все буквы английского алфавита.
            {
                if (guessedLetters.find(c) != string::npos) cout << ". "; // Если буква уже называлась, вместо неё выводится точка.
                else cout << c << " "; // Иначе выводится сама буква.
            }
            cout << endl; // Переход на новую строку.

            char guess; // Переменная для введённой буквы.
            cout << "Введите букву: "; // Приглашение к вводу.
            cin >> guess; // Считывает один символ с клавиатуры.

            if (guessedLetters.find(guess) != string::npos) // Если эта буква уже есть среди названных...
            {
                cout << "Вы уже называли эту букву!" << endl; // ...сообщает об этом.
                continue; // Пропускает остаток текущей итерации и возвращается к началу цикла.
            }

            if (alphabet.find(guess) == string::npos) // Если введённой буквы нет в английском алфавите...
            {
                cout << "Ошибка: введите букву на английском!" << endl; // ...сообщает об ошибке.
                continue; // Пропускает остаток текущей итерации.
            }

            guessedLetters += guess; // Добавляет введённую букву в список уже названных.
            bool found = false; // Флаг: найдена ли буква в загаданном слове.
            for (int i = 0; i < (int)secretWord.length(); i++) // Перебирает все позиции загаданного слова.
            {
                if (secretWord[i] == guess) // Если символ в secretWord совпадает с введённой буквой...
                {
                    currentWord[i] = guess; // ...открывает эту букву в текущем слове.
                    found = true; // Устанавливает флаг, что буква есть в слове.
                }
            }

            if (found) // Если буква найдена...
            {
                cout << "Есть такая буква!" << endl; // ...сообщает об успехе.
            }
            else // Если буквы в слове нет...
            {
                points--; // ...уменьшает количество очков на 1.
                cout << "Нет такой буквы. Вы теряете одно очко." << endl; // Сообщает о потере очка.
            }
        }

        if (currentWord == secretWord) // После выхода из цикла проверяет, угадано ли слово полностью.
        {
            cout << "\nПОЗДРАВЛЯЕМ! Вы угадали слово: " << secretWord << endl; // Поздравление и вывод загаданного слова.
            cout << "У вас осталось очков: " << points << endl; // Вывод оставшихся очков.
        }
        else // Иначе слово не угадано, а очки закончились.
        {
            cout << "\nИгра окончена. Вы проиграли." << endl; // Сообщение о проигрыше.
            cout << "Загаданное слово было: " << secretWord << endl; // Показывает загаданное слово.
        }

        system("PAUSE");
        return 0;
    }